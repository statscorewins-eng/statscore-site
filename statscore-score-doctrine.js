/*!
* =============================================================================
* STATS-CORE™
* Stream 9 — Score Doctrine
* -----------------------------------------------------------------------------
* File:
*     statscore-score-doctrine.js
*
* Purpose:
*     Define the official laws, boundaries, terminology, versioning,
*     confidence requirements, explainability requirements, and publication
*     requirements for all STATS-CORE athlete scores.
*
* Doctrine:
*     This file DOES NOT calculate scores.
*     This file defines what an official score is and what rules every
*     scoring matrix, engine, synthesizer, and consumer must obey.
*
* Version:
*     1.0.0
*
* Status:
*     CANON LOCKED
* =============================================================================
*/

(function (global) {
    'use strict';

    const AUTHORITY = global.STATScoreStream9Authority || null;
    const INTELLIGENCE_DOCTRINE = global.STATScoreIntelligenceDoctrine || null;

    const STATScoreScoreDoctrine = Object.freeze({

        doctrine_key: "STATSCORE_SCORE_DOCTRINE",

        stream_key: "STATSCORE_STREAM_9",

        doctrine_name: "STATS-CORE Score Doctrine",

        version: "1.0.0",

        doctrine_status: "CANON_LOCKED",

        requires_authority:
            "STATScoreStream9Authority",

        requires_intelligence_doctrine:
            "STATScoreIntelligenceDoctrine",

        authority_verified:
            Boolean(AUTHORITY && AUTHORITY.stream_number === 9),

        intelligence_doctrine_verified:
            Boolean(
                INTELLIGENCE_DOCTRINE &&
                INTELLIGENCE_DOCTRINE.doctrine_key === "STATSCORE_INTELLIGENCE_DOCTRINE"
            ),

        //----------------------------------------------------------------------
        // Score Definition
        //----------------------------------------------------------------------

        score_definition:
            "A STATS-CORE score is a governed numeric interpretation of athlete evidence produced by an authorized Stream 9 matrix or authority engine, versioned, explainable, confidence-aware, and suitable for official system consumption.",

        score_is: Object.freeze({

            evidence_based: true,

            matrix_authorized: true,

            versioned: true,

            confidence_aware: true,

            explainability_required: true,

            audit_ready: true,

            consumer_readable: true

        }),

        score_is_not: Object.freeze({

            raw_stat_total: true,

            dashboard_generated_number: true,

            visual_decoration: true,

            recruiter_preference_only: true,

            coach_opinion_only: true,

            ungoverned_average: true,

            manual_override_without_authority: true

        }),

        //----------------------------------------------------------------------
        // Score Types
        //----------------------------------------------------------------------

        score_types: Object.freeze({

            domain_score:
                "A score generated by one authorized matrix for one intelligence domain.",

            composite_score:
                "A score synthesized from multiple authorized domain scores under Stream 9 authority.",

            readiness_score:
                "A score reflecting current readiness using authorized readiness evidence and confidence logic.",

            pathway_support_score:
                "A score supporting route, level, eligibility, and development pathway recommendations.",

            ranking_support_score:
                "A score used to support ranking interpretation, not to create unexplained rankings.",

            program_fit_support_score:
                "A score used to support fit between athlete evidence and program need context."

        }),

        //----------------------------------------------------------------------
        // Score Range Doctrine
        //----------------------------------------------------------------------

        score_range: Object.freeze({

            minimum: 0,

            maximum: 100,

            decimal_precision: 2,

            out_of_range_allowed: false,

            null_score_allowed_when_evidence_insufficient: true,

            insufficient_evidence_status:
                "INSUFFICIENT_EVIDENCE"

        }),

        //----------------------------------------------------------------------
        // Confidence Requirement
        //----------------------------------------------------------------------

        confidence_doctrine: Object.freeze({

            confidence_required_for_official_scores: true,

            confidence_is_independent_from_score: true,

            high_score_low_confidence_allowed: true,

            low_score_high_confidence_allowed: true,

            moderate_score_high_confidence_allowed: true,

            incomplete_score_insufficient_confidence_allowed: true,

            confidence_may_not_be_replaced_by_score: true

        }),

        //----------------------------------------------------------------------
        // Explainability Requirement
        //----------------------------------------------------------------------

        explainability_doctrine: Object.freeze({

            explanation_required_for_official_scores: true,

            score_without_explanation_is_unofficial: true,

            explanation_must_include_evidence_used: true,

            explanation_must_include_missing_evidence_when_applicable: true,

            explanation_must_include_confidence_factors: true,

            explanation_must_include_next_action_when_applicable: true

        }),

        //----------------------------------------------------------------------
        // Weighting Doctrine
        //----------------------------------------------------------------------

        weighting_doctrine: Object.freeze({

            weighting_required_for_matrix_scores: true,

            weights_must_be_declared_in_matrix: true,

            hidden_weights_allowed: false,

            dashboard_weighting_allowed: false,

            consumer_weight_adjustment_allowed: false,

            matrix_version_must_change_when_weights_change: true

        }),

        //----------------------------------------------------------------------
        // Publication Doctrine
        //----------------------------------------------------------------------

        publication_doctrine: Object.freeze({

            official_scores_must_publish_through_stream_9: true,

            official_composite_scores_must_publish_through_composite_authority: true,

            consumers_may_display_scores: true,

            consumers_may_store_score_snapshots: true,

            consumers_may_recalculate_scores: false,

            consumers_may_modify_scores: false,

            consumers_may_override_confidence: false,

            consumers_may_generate_official_recommendations: false

        }),

        //----------------------------------------------------------------------
        // Score Integrity Rules
        //----------------------------------------------------------------------

        integrity_rules: Object.freeze({

            athlete_id_required: true,

            snapshot_id_required: true,

            matrix_version_required: true,

            doctrine_version_required: true,

            generated_at_required: true,

            evidence_reference_required: true,

            confidence_required: true,

            explainability_required: true,

            unauthorized_score_status:
                "UNOFFICIAL",

            invalid_score_status:
                "INVALID_SCORE",

            insufficient_score_status:
                "INSUFFICIENT_EVIDENCE"

        }),

        //----------------------------------------------------------------------
        // Validation
        //----------------------------------------------------------------------

        validateAuthority: function () {
            return Boolean(
                global.STATScoreStream9Authority &&
                global.STATScoreStream9Authority.stream_number === 9 &&
                global.STATScoreStream9Authority.operational_state === "ACTIVE"
            );
        },

        validateIntelligenceDoctrine: function () {
            return Boolean(
                global.STATScoreIntelligenceDoctrine &&
                global.STATScoreIntelligenceDoctrine.doctrine_key === "STATSCORE_INTELLIGENCE_DOCTRINE" &&
                global.STATScoreIntelligenceDoctrine.doctrine_status === "CANON_LOCKED"
            );
        },

        isScoreInRange: function (score) {
            if (score === null && this.score_range.null_score_allowed_when_evidence_insufficient) {
                return true;
            }

            if (typeof score !== "number" || Number.isNaN(score)) {
                return false;
            }

            return score >= this.score_range.minimum &&
                   score <= this.score_range.maximum;
        },

        normalizeScore: function (score) {
            if (score === null && this.score_range.null_score_allowed_when_evidence_insufficient) {
                return null;
            }

            if (typeof score !== "number" || Number.isNaN(score)) {
                return null;
            }

            const bounded = Math.max(
                this.score_range.minimum,
                Math.min(this.score_range.maximum, score)
            );

            return Number(bounded.toFixed(this.score_range.decimal_precision));
        },

        getDoctrineStatus: function () {
            return {
                doctrine_key: this.doctrine_key,
                version: this.version,
                doctrine_status: this.doctrine_status,
                authority_verified: this.validateAuthority(),
                intelligence_doctrine_verified: this.validateIntelligenceDoctrine(),
                official_scores_must_publish_through_stream_9:
                    this.publication_doctrine.official_scores_must_publish_through_stream_9,
                consumers_may_recalculate_scores:
                    this.publication_doctrine.consumers_may_recalculate_scores
            };
        }

    });

    Object.freeze(STATScoreScoreDoctrine);

    global.STATScoreScoreDoctrine = STATScoreScoreDoctrine;

})(window); 
